const dictionaries: Record<Language, Partial<Record<MessageKey, Message>>> = { en, zh };

const interpolate = (text: string, vars?: MessageVars) =>
  vars ? text.replace(/\{(\w+)\}/g, (whole, key: string) => (vars[key] === undefined ? whole : String(vars[key]))) : text;

/** The message for `key` in `language`, with `{name}` placeholders filled from `vars`. */
export function translate(language: Language, key: MessageKey, vars?: MessageVars): string {
  const message = dictionaries[language]?.[key] ?? en[key];
  return typeof message === "function" ? message(vars ?? {}) : interpolate(message, vars);
}

/** A translator bound to one language, for surfaces that render many strings. */
export function translator(language: Language) {
  return (key: MessageKey, vars?: MessageVars) => translate(language, key, vars);
}

export type Translator = ReturnType<typeof translator>;
